#include "vectors.h"

int	is_equal(t_vector *a, t_vector *b)
{
	return (fabs(a->x - b->x) < 0.000001
		&& fabs(a->y - b->y) < 0.000001
		&& fabs(a->z - b->z) < 0.000001
		&& fabs(a->w - b->w) < 0.000001);
}
